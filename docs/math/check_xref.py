"""check_xref.py - keep the math slides and the code in step.

The math slides (math_slides.tex) give each slide an ID (\\slideid{FP}) and number the key formulas <ID>.<n>
(\\tag{FP.2} in displays, \\eqtag{ST1.1} at the end of a text line). The code cites them in a comment block right
above the function that implements them:

    # Math: FP.1, FP.2 (slide FP): ...
    def besselian_offsets(...):

Formula numbers (FP.2), ranges (ST2.1-ST2.3) and slide IDs after "slide"/"slides" are recognised. This script
  - reports references to formulas or slides that do not exist (exit code 1),
  - lists the formulas no code cites (a reminder, not an error),
  - writes xref_table.tex: the appendix slide "Code references" (formula -> module.function).

    python3 docs/math/check_xref.py          (also run by make here, and by tests/test_math_xref.py)
"""
import glob, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "src", "pysyzygos")
TAG = re.compile(r"\\(?:tag|eqtag)\{([A-Z]{2}\d?\.\d+)\}")
SLIDE = re.compile(r"\\begin\{frame\}(?:\[[^\]]*\])?\{([^}]*)\}\\slideid\{([A-Z]{2}\d?)\}")
REF = re.compile(r"\b([A-Z]{2}\d?)\.(\d+)(?:-\1\.(\d+))?\b")
SLIDEREF = re.compile(r"\bslides?\s+((?:[A-Z]{2}\d?)(?:\s*,\s*[A-Z]{2}\d?)*)")


def slides(tex=os.path.join(HERE, "math_slides.tex")):
    """({ID: title}, {formula: ID}) from the slides."""
    s = open(tex, encoding="utf-8").read()
    ids = {m.group(2): m.group(1) for m in SLIDE.finditer(s)}
    tags = {}
    for m in TAG.finditer(s):
        if m.group(1) in tags:
            raise SystemExit(f"formula number {m.group(1)} used twice in {tex}")
        tags[m.group(1)] = m.group(1).split(".")[0]
    return ids, tags


def code_refs(src=SRC):
    """[(module, function, formulas, slide IDs, line)] from the '# Math:' comment blocks above functions."""
    out = []
    for path in sorted(glob.glob(os.path.join(src, "*.py"))):
        lines = open(path, encoding="utf-8").read().split("\n")
        for i, line in enumerate(lines):
            if not line.startswith("# Math:"):
                continue
            text, j = line, i + 1
            while j < len(lines) and lines[j].startswith("#"):
                text += " " + lines[j].lstrip("# ")
                j += 1
            m = re.match(r"(?:async\s+)?def\s+(\w+)", lines[j]) if j < len(lines) else None
            func = m.group(1) if m else "?"
            formulas = []
            for r in REF.finditer(text):
                a, b = int(r.group(2)), int(r.group(3) or r.group(2))
                formulas += [f"{r.group(1)}.{k}" for k in range(a, b + 1)]
            sl = [x.strip() for r in SLIDEREF.finditer(text) for x in r.group(1).split(",")]
            out.append((os.path.basename(path)[:-3], func, formulas, sl, i + 1))
    return out


def check(tex=os.path.join(HERE, "math_slides.tex"), src=SRC):
    """(errors, uncited formulas, table rows {formula: [module.function]})."""
    ids, tags = slides(tex)
    errors, cited = [], {}
    for mod, func, formulas, sl, line in code_refs(src):
        where = f"{mod}.py:{line} ({func})"
        if func == "?":
            errors.append(f"{where}: no function right below the '# Math:' comment")
        for f in formulas:
            if f not in tags:
                errors.append(f"{where}: formula {f} is not on the slides")
            cited.setdefault(f, []).append(f"{mod}.{func}")
        for x in sl:
            if x not in ids:
                errors.append(f"{where}: slide {x} does not exist")
    uncited = [t for t in tags if t not in cited]
    return errors, uncited, {t: cited.get(t, []) for t in tags}, ids


def _tt(s):
    return "\\texttt{" + s.replace("_", "\\_") + "}"


def write_table(rows, ids, out=os.path.join(HERE, "xref_table.tex")):
    """The appendix slide: formula, slide, the functions that implement it."""
    lines = ["% generated by check_xref.py: do not edit (formula -> code, from the '# Math:' comments)",
             "\\begin{frame}{Code references}", "  \\scriptsize\\renewcommand{\\arraystretch}{0.92}",
             "  \\begin{tabular}{@{}l l >{\\raggedright\\arraybackslash}p{0.74\\textwidth}@{}}",
             "    \\textbf{Formula} & \\textbf{Slide} & \\textbf{Code (src/pysyzygos)} \\\\ \\midrule"]
    for t in sorted(rows, key=lambda t: (list(ids).index(t.split(".")[0]) if t.split(".")[0] in ids else 99,
                                         int(t.split(".")[1]))):
        sid = t.split(".")[0]
        funcs = ", ".join(_tt(f) for f in dict.fromkeys(rows[t])) or "---"
        lines.append(f"    {t} & {sid} & {funcs} \\\\")
    lines += ["  \\end{tabular}", "\\end{frame}", ""]
    tmp = out + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    os.replace(tmp, out)


def main():
    errors, uncited, rows, ids = check()
    for e in errors:
        print("ERROR", e)
    if uncited:
        print("not cited in the code:", ", ".join(uncited))
    write_table(rows, ids)
    print(f"{len(rows)} formulas on {len(ids)} slides, {sum(1 for r in rows.values() if r)} cited; "
          f"{len(errors)} error(s); xref_table.tex written")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
