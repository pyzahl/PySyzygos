### CONFIG OBSERVER: sites, their view and equipment

# The site comes from sites.py (your sites, not in git), else from sites_example.py (in pysyzygos/templates). Choose one by name with the
# environment variable PYSYZYGOS_SITE (default: default_site in that file). A site has lat, lon, ele and may set any of
# the keys below; the values here are the defaults for keys a site leaves out.
try:
    from sites import sites, default_site
except ImportError:
    from pysyzygos.templates.sites_example import sites, default_site
site_name = _os.environ.get("PYSYZYGOS_SITE", default_site)
if site_name not in sites:
    raise SystemExit(f"site {site_name!r} not in sites.py (known: {', '.join(sites)})")
site = sites[site_name]

LAT = site["lat"]                                  # latitude, deg
LON = site["lon"]                                  # longitude, deg, negative is west
ELE_MSL = site["ele"]                              # elevation, m, as in sites.py (above mean sea level)
GEOID_M = site.get("geoid_m", 0.0)                 # geoid above the WGS84 ellipsoid there (sites.py, filled when saved)
ELE = ELE_MSL + GEOID_M                            # height above the WGS84 ellipsoid, m: what the geometry uses

# view
MIN_STAR_ALT = site.get("min_alt", 10.0)           # deg, lowest usable star altitude (trees, houses, haze)
MAX_SUN_ALT = site.get("max_sun_alt", 0.0)         # deg, the Sun must be below this; events with the Sun above -12
                                                   # are marked as twilight (☼ -8°); -12 or lower for faint stars only
max_shadow_dist = site.get("reach_km", max_shadow_dist)   # km, travel distance from the site (default: search setup)
ALT_MARGIN = 3.0                                   # early gate is looser than the final one, never rejects a real event

# atmospheric extinction for lower altitudes, mag per airmass: a star at altitude h counts as fainter by
# atm_extinction * (airmass(h) - 1) in the observability test (0 = off; ~0.2 typical, ~0.3 hazy or light-polluted).
# A site's `extinction` key overrides it.
atm_extinction = 0.0

# equipment: OWC's General Observability Criterion. An event is observable if
#   StarMag < 5 log10(aperture_cm) + 2.5 log10(MaxDuration / frames) + 8.5 + mag_adjust
# (mag_adjust > 0 for better conditions: dark sky, sensitive camera; < 0 for worse), optionally with atmospheric
# extinction at the star's altitude. The faintest star searched (MAG_MIN) is the one that is observable at the
# longest usable exposure max_exp_s (= MaxDuration / frames), unless the site gives mag_limit.
pick_aperture_cm = site.get("aperture_cm", 25.0)   # telescope aperture, cm
pick_frames = site.get("frames", 4)                # detection frames
pick_mag_adjust = site.get("mag_adjust", 0.0)      # OWC MagAdjust, mag
pick_extinction = site.get("extinction", atm_extinction)   # mag per airmass (see atm_extinction above)
pick_min_dur_s = site.get("min_dur_s", 0.4)        # hard limit: shortest event, s
pick_max_exp_s = site.get("max_exp_s", 0.64)       # longest usable exposure, s (25 cm: G 15.0, as OWC)
_lim = (5 * __import__("math").log10(pick_aperture_cm) + 2.5 * __import__("math").log10(pick_max_exp_s)
        + 8.5 + pick_mag_adjust)
MAG_MIN = min(site.get("mag_limit", round(_lim, 1)), gaia_local_gmax)   # faintest star searched
pick_cam_limit = MAG_MIN                           # same limit for the pick tool

# camera, for the event preview: field of view from the focal length and the sensor size
camera_focal_mm = site.get("focal_mm", 100.0 * pick_aperture_cm)   # focal length, mm (default f/10)
camera_sensor_mm = tuple(site.get("sensor_mm", (5.6, 3.2)))        # sensor width, height, mm (5.6 x 3.2: e.g. IMX290)

